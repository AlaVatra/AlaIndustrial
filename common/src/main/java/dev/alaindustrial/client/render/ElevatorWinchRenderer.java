package dev.alaindustrial.client.render;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.math.Axis;
import dev.alaindustrial.Industrialization;
import dev.alaindustrial.block.ElevatorStationBlock;
import dev.alaindustrial.block.entity.ElevatorWinchBlockEntity;
import dev.alaindustrial.compat.client.Poses;
import dev.alaindustrial.core.elevator.ElevatorTrip;
import java.util.List;
import net.minecraft.client.renderer.Sheets;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.blockentity.BlockEntityRenderer;
import net.minecraft.client.renderer.blockentity.BlockEntityRendererProvider;
import net.minecraft.client.renderer.blockentity.state.BlockEntityRenderState;
import net.minecraft.client.renderer.feature.ModelFeatureRenderer;
import net.minecraft.client.renderer.rendertype.RenderType;
import net.minecraft.client.renderer.state.level.CameraRenderState;
import net.minecraft.client.renderer.texture.TextureAtlasSprite;
import net.minecraft.client.resources.model.sprite.SpriteGetter;
import net.minecraft.client.resources.model.sprite.SpriteId;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.util.LightCoordsUtil;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.Vec3;
import org.jspecify.annotations.Nullable;

/**
 * The elevator's moving parts (MOD-769), drawn from the winch: the cabin where its trip has it at this frame, inside
 * the glass tube under the winch, and the rope from the winch's bottom down to the cabin's roof.
 *
 * <p>Where the cabin is comes from the winch ({@link ElevatorWinchBlockEntity#drawnCabinHeight}): the trip and the
 * game clock, at the frame's partial tick, so the cabin glides without a packet per tick; read on the clock the
 * entities are drawn on, so the player riding it is drawn, and looks out, from inside it.
 *
 * <p>The cabin's open side (no low wall, no handrail) faces the doorway of the station it stands at, or of the one it
 * is going to: stations of one shaft may face different ways, and the cabin turns to the next one while the doors are
 * shut. The geometry is the designer's ({@link ElevatorGeometry}, generated by
 * {@code tools/model_sources/elevator/build_elevator.py}) on the cabin sheet {@code elevator_cabin}; it is opaque, so
 * it is drawn cut-out, and the glass of the tube round it is the static models' own translucent layer.
 */
public final class ElevatorWinchRenderer
		implements BlockEntityRenderer<ElevatorWinchBlockEntity, ElevatorWinchRenderer.State>,
			RenderBoxProvider<ElevatorWinchBlockEntity> {

	private static final SpriteId SPRITE = Sheets.BLOCKS_MAPPER.apply(Industrialization.id("elevator_cabin"));
	private static final RenderType TYPE = SPRITE.renderType(ignored -> Sheets.cutoutBlockItemSheet());

	private static final CubeMesh CABIN = new CubeMesh(ElevatorGeometry.CABIN, 0.0F);
	private static final CubeMesh ROPE = new CubeMesh(ElevatorGeometry.ROPE, 0.0F);
	/** The cabin's height, blocks: the rope leaves its roof there. */
	private static final float CABIN_HEIGHT = 2.0F;

	private final SpriteGetter sprites;

	public ElevatorWinchRenderer(BlockEntityRendererProvider.Context context) {
		this.sprites = context.sprites();
	}

	/** Render state: only primitives, no block-entity reference. */
	public static final class State extends BlockEntityRenderState {
		boolean visible;
		/** The cabin floor's height over the winch's block, blocks (negative: under it). */
		float cabin;
		int cabinLight;
		/** Quarter turns of the cabin, as a blockstate's {@code y} turns a model drawn facing north. */
		int frontQuarter;
	}

	@Override
	public State createRenderState() {
		return new State();
	}

	@Override
	public void extractRenderState(ElevatorWinchBlockEntity entity, State state, float partialTicks,
			Vec3 cameraPosition, ModelFeatureRenderer.@Nullable CrumblingOverlay breakProgress) {
		BlockEntityRenderer.super.extractRenderState(entity, state, partialTicks, cameraPosition, breakProgress);
		Level level = entity.getLevel();
		List<Integer> floors = entity.floors();
		double floor = level == null ? Double.NaN : entity.drawnCabinHeight(level.getGameTime(), partialTicks);
		state.visible = level != null && !Double.isNaN(floor) && !floors.isEmpty();
		if (!state.visible) {
			return;
		}
		state.cabin = (float) (floor - entity.getBlockPos().getY());
		state.cabinLight = LightCoordsUtil.getLightCoords(level, entity.cabinCell(floor).above());
		ElevatorTrip trip = entity.trip();
		BlockState station = level.getBlockState(entity.cabinCell(trip != null ? trip.to() : floor));
		Direction front = station.getBlock() instanceof ElevatorStationBlock
				? station.getValue(ElevatorStationBlock.FACING) : Direction.NORTH;
		state.frontQuarter = (front.get2DDataValue() + 2) % 4;
	}

	@Override
	public void submit(State state, PoseStack poseStack, SubmitNodeCollector collector, CameraRenderState camera) {
		if (!state.visible) {
			return;
		}
		TextureAtlasSprite sprite = this.sprites.get(SPRITE);
		int light = state.cabinLight;
		poseStack.pushPose();
		poseStack.translate(0.5F, state.cabin, 0.5F);
		Poses.rotate(poseStack, Axis.YP.rotationDegrees(-90.0F * state.frontQuarter));
		poseStack.translate(-0.5F, 0.0F, -0.5F);
		collector.submitCustomGeometry(poseStack, TYPE, (pose, consumer) -> CABIN.emit(pose, consumer, sprite, light));
		poseStack.popPose();
		rope(poseStack, collector, sprite, state.cabin + CABIN_HEIGHT, 0.0F, light);
	}

	/** A rope from {@code bottom} up to {@code top} (heights over the winch's block): whole blocks, then the rest. */
	private static void rope(PoseStack poseStack, SubmitNodeCollector collector, TextureAtlasSprite sprite,
			float bottom, float top, int light) {
		float length = top - bottom;
		if (length <= 0.01F) {
			return;
		}
		int whole = (int) Math.floor(length);
		for (int k = 0; k < whole; k++) {
			poseStack.pushPose();
			poseStack.translate(0.0F, bottom + k, 0.0F);
			collector.submitCustomGeometry(poseStack, TYPE, (pose, consumer) -> ROPE.emit(pose, consumer, sprite,
					light));
			poseStack.popPose();
		}
		float rest = length - whole;
		if (rest > 0.01F) {
			poseStack.pushPose();
			poseStack.translate(0.0F, bottom + whole, 0.0F);
			poseStack.scale(1.0F, rest, 1.0F);
			collector.submitCustomGeometry(poseStack, TYPE, (pose, consumer) -> ROPE.emit(pose, consumer, sprite,
					light));
			poseStack.popPose();
		}
	}

	/** The cabin runs the whole shaft under the winch. */
	@Override
	public boolean shouldRenderOffScreen() {
		return true;
	}

	/**
	 * The box NeoForge and Forge test against the view frustum (MOD-633): the glass tube, from under the lowest floor
	 * to over the winch. No {@code @Override}: only NeoForge's interface declares it
	 * ({@code OffScreenRendererBoxTest}).
	 */
	public AABB getRenderBoundingBox(ElevatorWinchBlockEntity blockEntity) {
		BlockPos winch = blockEntity.getBlockPos();
		List<Integer> floors = blockEntity.floors();
		int bottom = floors.isEmpty() ? winch.getY() : floors.getFirst();
		return new AABB(winch.getX(), bottom - 1.0D, winch.getZ(), winch.getX() + 1.0D, winch.getY() + 1.0D,
				winch.getZ() + 1.0D);
	}

	@Override
	public int getViewDistance() {
		return 96;
	}
}
